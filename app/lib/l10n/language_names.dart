/// Langues de traduction, celle de l'application d'abord, puis par nom.
List<String> translationLanguages(String appLanguage) {
  String nameOf(String code) => languageName(code, appLanguage) ?? code;
  return [..._translationLanguages]..sort((a, b) {
    if (a == appLanguage) return -1;
    if (b == appLanguage) return 1;
    return nameOf(a).compareTo(nameOf(b));
  });
}

/// Nom de la langue [code], un code ISO 639-1 ou une variante propre aux
/// fournisseurs (`lat`, `qc`, `scn`), dans la langue [appLanguage].
/// Retourne `null` si elle n'est pas connue.
String? languageName(String? code, String appLanguage) {
  final names = _names[code];
  return names?[appLanguage] ?? names?['en'];
}
